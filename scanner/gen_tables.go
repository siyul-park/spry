//go:build ignore

// gen_tables generates tables.go from testdata/cpython/unicode.json: the
// identifier and printable character tables of CPython's unicodedata.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
	"unicode"
)

type data struct {
	Version  string     `json:"unidata_version"`
	IDStart  [][2]int32 `json:"id_start"`
	IDCont   [][2]int32 `json:"id_continue"`
	Printabl [][2]int32 `json:"printable"`
}

func main() {
	raw, err := os.ReadFile("testdata/cpython/unicode.json")
	if err != nil {
		log.Fatal(err)
	}
	var d data
	if err := json.Unmarshal(raw, &d); err != nil {
		log.Fatal(err)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by gen_tables.go; DO NOT EDIT.\n\n")
	b.WriteString("package scanner\n\nimport \"unicode\"\n\n")
	fmt.Fprintf(&b, "// unicodeVersion is the Unicode version of the tables.\nconst unicodeVersion = %q\n\n", d.Version)
	table(&b, "idStart", "XID_Start plus underscore", d.IDStart)
	table(&b, "idContinue", "XID_Continue", d.IDCont)
	table(&b, "printable", "the characters CPython's str.isprintable accepts", d.Printabl)

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("tables.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func table(b *bytes.Buffer, name, doc string, ranges [][2]int32) {
	var r16 []unicode.Range16
	var r32 []unicode.Range32
	latin := 0
	for _, r := range ranges {
		lo, hi := r[0], r[1]
		switch {
		case hi <= 0xFFFF:
			r16 = append(r16, unicode.Range16{Lo: uint16(lo), Hi: uint16(hi), Stride: 1})
			if hi <= unicode.MaxLatin1 {
				latin++
			}
		case lo > 0xFFFF:
			r32 = append(r32, unicode.Range32{Lo: uint32(lo), Hi: uint32(hi), Stride: 1})
		default:
			r16 = append(r16, unicode.Range16{Lo: uint16(lo), Hi: 0xFFFF, Stride: 1})
			r32 = append(r32, unicode.Range32{Lo: 0x10000, Hi: uint32(hi), Stride: 1})
		}
	}
	fmt.Fprintf(b, "// %s holds %s.\nvar %s = &unicode.RangeTable{\n", name, doc, name)
	b.WriteString("R16: []unicode.Range16{\n")
	for _, r := range r16 {
		fmt.Fprintf(b, "{Lo: %#04x, Hi: %#04x, Stride: 1},\n", r.Lo, r.Hi)
	}
	b.WriteString("},\nR32: []unicode.Range32{\n")
	for _, r := range r32 {
		fmt.Fprintf(b, "{Lo: %#x, Hi: %#x, Stride: 1},\n", r.Lo, r.Hi)
	}
	fmt.Fprintf(b, "},\nLatinOffset: %d,\n}\n\n", latin)
}
