//go:build ignore

// gen_stdlib generates stdlib.go: the sorted sys.stdlib_module_names of the
// CPython 3.14 interpreter that internal/cpython.Lookup finds. The loader
// reports a known standard-library module that spry does not ship as TYP121.
package main

import (
	"bytes"
	"context"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"

	"github.com/siyul-park/spry/internal/cpython"
)

func main() {
	python, err := cpython.Lookup()
	if err != nil {
		log.Fatal(err)
	}
	const script = "import sys\nprint('\\n'.join(sorted(sys.stdlib_module_names)))"
	res, err := cpython.Run(context.Background(), python, "", nil, "-I", "-c", script)
	if err != nil || res.ExitCode != 0 {
		log.Fatalf("run %s: %v %s", python, err, res.Stderr)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by gen_stdlib.go; DO NOT EDIT.\n\npackage types\n\n")
	b.WriteString("// stdlibModules holds sys.stdlib_module_names of CPython 3.14.\nvar stdlibModules = map[string]bool{\n")
	for name := range strings.SplitSeq(strings.TrimSpace(res.Stdout), "\n") {
		fmt.Fprintf(&b, "%q: true,\n", name)
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("stdlib.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
