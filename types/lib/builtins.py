class map[T](Iterator[T]):
    _f: Callable[..., T]
    _its: list[Iterator[Any]]

    @overload
    def __init__[A](self, function: Callable[[A], T], a: Iterable[A], /) -> None: ...
    @overload
    def __init__[A, B](
        self, function: Callable[[A, B], T], a: Iterable[A], b: Iterable[B], /
    ) -> None: ...
    def __init__(self, function, *iterables):
        self._f = function
        self._its = [iter(it) for it in iterables]

    def __iter__(self) -> Self:
        return self

    def __next__(self) -> T:
        args = [next(it) for it in self._its]
        return self._f(*args)


class filter[T](Iterator[T]):
    _f: Callable[[T], object] | None
    _it: Iterator[T]

    @overload
    def __init__(self, function: None, iterable: Iterable[T], /) -> None: ...
    @overload
    def __init__(
        self, function: Callable[[T], object], iterable: Iterable[T], /
    ) -> None: ...
    def __init__(self, function, iterable):
        self._f = function
        self._it = iter(iterable)

    def __iter__(self) -> Self:
        return self

    def __next__(self) -> T:
        while True:
            value = next(self._it)
            if self._f is None:
                if value:
                    return value
            elif self._f(value):
                return value


class reversed[T](Iterator[T]):
    _seq: Sequence[T]
    _i: int

    def __init__(self, sequence: Sequence[T], /) -> None:
        self._seq = sequence
        self._i = len(sequence)

    def __iter__(self) -> Self:
        return self

    def __next__(self) -> T:
        if self._i <= 0:
            raise StopIteration
        self._i = self._i - 1
        return self._seq[self._i]


