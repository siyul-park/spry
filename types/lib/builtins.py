# Prelude: the builtins that call back into Python. A host function must not
# re-enter the VM, so a call whose arguments hold instances of classes of the
# program, or that passes key=, resolves to one of these functions, which are
# compiled with the program.
def __sorted__(iterable, key=None, reverse=False):
    items = list(iterable)
    n = len(items)
    keys = []
    for x in items:
        if key is None:
            keys.append(x)
        else:
            keys.append(key(x))
    order = list(range(n))
    width = 1
    while width < n:
        merged = []
        start = 0
        while start < n:
            mid = min(start + width, n)
            end = min(start + 2 * width, n)
            i = start
            j = mid
            while i < mid and j < end:
                if reverse:
                    right = keys[order[i]] < keys[order[j]]
                else:
                    right = keys[order[j]] < keys[order[i]]
                if right:
                    merged.append(order[j])
                    j += 1
                else:
                    merged.append(order[i])
                    i += 1
            while i < mid:
                merged.append(order[i])
                i += 1
            while j < end:
                merged.append(order[j])
                j += 1
            start += 2 * width
        order = merged
        width *= 2
    out = []
    for i in order:
        out.append(items[i])
    return out


