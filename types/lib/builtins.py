class enumerate[T](Iterator[tuple[int, T]]):
    _it: Iterator[T]
    _i: int

    def __init__(self, iterable: Iterable[T], start: int = 0) -> None:
        self._it = iter(iterable)
        self._i = start

    def __iter__(self) -> Self:
        return self

    def __next__(self) -> tuple[int, T]:
        value = next(self._it)
        i = self._i
        self._i = i + 1
        return (i, value)


