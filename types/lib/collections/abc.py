"""Stub of collections.abc: the protocols and abstract classes that the
builtin classes implement."""

from typing import Any, Protocol, Self, _SpecialForm, overload, runtime_checkable

Callable: _SpecialForm


@runtime_checkable
class Hashable(Protocol):
    def __hash__(self) -> int: ...


@runtime_checkable
class Sized(Protocol):
    def __len__(self) -> int: ...


@runtime_checkable
class Iterable[T](Protocol):
    def __iter__(self) -> Iterator[T]: ...


@runtime_checkable
class Iterator[T](Iterable[T], Protocol):
    def __next__(self) -> T: ...
    def __iter__(self) -> Self: ...


class Generator[Y, S, R](Iterator[Y], Protocol):
    def __next__(self) -> Y: ...
    def send(self, value: S, /) -> Y: ...
    def throw(self, typ: object, val: object = None, tb: object = None, /) -> Y: ...
    def close(self) -> None: ...


@runtime_checkable
class Container[T](Protocol):
    def __contains__(self, x: object, /) -> bool: ...


@runtime_checkable
class Collection[T](Iterable[T], Container[T], Sized, Protocol): ...


class Sequence[T](Collection[T]):
    @overload
    def __getitem__(self, index: int, /) -> T: ...
    @overload
    def __getitem__(self, index: slice, /) -> Sequence[T]: ...
    def index(self, value: object, start: int = 0, stop: int = ..., /) -> int: ...
    def count(self, value: object, /) -> int: ...
    def __reversed__(self) -> Iterator[T]: ...


class MutableSequence[T](Sequence[T]):
    @overload
    def __setitem__(self, index: int, value: T, /) -> None: ...
    @overload
    def __setitem__(self, index: slice, value: Iterable[T], /) -> None: ...
    def __delitem__(self, index: int | slice, /) -> None: ...
    def insert(self, index: int, value: T, /) -> None: ...
    def append(self, value: T, /) -> None: ...
    def extend(self, values: Iterable[T], /) -> None: ...
    def pop(self, index: int = -1, /) -> T: ...
    def remove(self, value: T, /) -> None: ...
    def reverse(self) -> None: ...
    def clear(self) -> None: ...


class Set[T](Collection[T]):
    def __le__(self, other: Set[Any], /) -> bool: ...
    def __lt__(self, other: Set[Any], /) -> bool: ...
    def __ge__(self, other: Set[Any], /) -> bool: ...
    def __gt__(self, other: Set[Any], /) -> bool: ...
    def __and__(self, other: Set[Any], /) -> Set[T]: ...
    def __or__[U](self, other: Set[U], /) -> Set[T | U]: ...
    def __sub__(self, other: Set[Any], /) -> Set[T]: ...
    def __xor__[U](self, other: Set[U], /) -> Set[T | U]: ...
    def isdisjoint(self, other: Iterable[Any], /) -> bool: ...


class KeysView[K](Set[K]): ...


class ValuesView[V](Collection[V]): ...


class ItemsView[K, V](Set[tuple[K, V]]): ...


class Mapping[K, V](Collection[K]):
    def __getitem__(self, key: K, /) -> V: ...
    @overload
    def get(self, key: K, /) -> V | None: ...
    @overload
    def get[D](self, key: K, default: D, /) -> V | D: ...
    def items(self) -> ItemsView[K, V]: ...
    def keys(self) -> KeysView[K]: ...
    def values(self) -> ValuesView[V]: ...


class MutableMapping[K, V](Mapping[K, V]):
    def __setitem__(self, key: K, value: V, /) -> None: ...
    def __delitem__(self, key: K, /) -> None: ...
    def clear(self) -> None: ...
    @overload
    def pop(self, key: K, /) -> V: ...
    @overload
    def pop[D](self, key: K, default: V | D, /) -> V | D: ...
    def setdefault(self, key: K, default: V, /) -> V: ...
    def update(self, other: Mapping[K, V], /) -> None: ...


class Awaitable[T](Protocol):
    def __await__(self) -> Generator[Any, Any, T]: ...


class Coroutine[Y, S, R](Awaitable[R], Protocol):
    def send(self, value: S, /) -> Y: ...
    def throw(self, typ: object, val: object = None, tb: object = None, /) -> Y: ...
    def close(self) -> None: ...
